export async function seedNews(db: Db, today: string): Promise<number> {
  await db.insert(news).values(
    NEWS.map(({ daysAgo, time, ...item }) => ({
      ...item,
      source: 'site' as const,
      publishedAt: zonedTimeToUtc(addDays(today, -daysAgo), time, 'Europe/Moscow'),
    })),
  );
  return NEWS.length;
}
